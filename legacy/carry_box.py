class Probe:
    """One compiled model used for thousands of geometric trials.

    Compiling the G1 takes a noticeable fraction of a second, so the box is
    resized and repositioned at runtime instead. Resizing a primitive geom
    is safe as long as it only ever SHRINKS from the compiled size, because
    the broadphase bound is computed at compile time; the scene is therefore
    compiled with the largest box in the sweep.
    """

    def __init__(self, path):
        self.model = mujoco.MjModel.from_xml_path(path)
        self.data = mujoco.MjData(self.model)
        self.rig = Rig(self.model)
        self.box_gid = mujoco.mj_name2id(self.model, mujoco.mjtObj.mjOBJ_GEOM,
                                         "box_geom")
        jid = mujoco.mj_name2id(self.model, mujoco.mjtObj.mjOBJ_JOINT,
                                "box_free")
        self.box_q = int(self.model.jnt_qposadr[jid])
        self.q0 = self.model.qpos0.copy()
        for e in ("box_stand", "box_hold"):
            i = mujoco.mj_name2id(self.model, mujoco.mjtObj.mjOBJ_EQUALITY, e)
            if i >= 0:
                self.data.eq_active[i] = 0      # geometry only, no solver pull

    def resize(self, hx, hy, hz):
        self.model.geom_size[self.box_gid] = (hx, hy, hz)
        self.model.geom_rbound[self.box_gid] = float(
            np.linalg.norm([hx, hy, hz]))
        try:
            self.model.geom_aabb[self.box_gid] = (0., 0., 0., hx, hy, hz)
        except Exception:
            pass

    def place(self, pose, cx, cz):
        d = self.data
        d.qpos[:] = self.q0
        d.qvel[:] = 0.
        d.qpos[self.rig.qadr] = pose
        d.qpos[self.box_q:self.box_q + 7] = (cx, 0., cz, 1., 0., 0., 0.)
        mujoco.mj_forward(self.model, d)

    def hits(self, pose, cx, cz):
        self.place(pose, cx, cz)
        return self.rig.zone_hits(self.data, self.box_gid)


def measure_chest_surface(probe, hx, hy, hz, cz):
    """Where the box's back face has to be before the chest pad feels it.

    Walk the box backwards a millimetre at a time and watch for the first
    contact that lands inside the chest zone. No guessing, no hand-written
    offsets.
    """
    probe.resize(hx, hy, hz)
    rest = probe.rig.pose(0., 0., 0., 0.)
    ci = PATCHES.index("chest")
    first_touch, first_chest = None, None
    for back in np.arange(0.24, -0.02, -0.002):
        hits, _, _ = probe.hits(rest, float(back) + hx, cz)
        if first_touch is None and hits.sum() > 0:
            first_touch = float(back)
        if hits[ci] > 0:
            first_chest = float(back)
            break
    return first_chest, first_touch


def physics_trial(model, rig, target, seconds=2.5):
    """Drive the pose with the real controller and read the real sensors.

    The box is pinned exactly the way the run pins it, so what this measures
    is what the run will do. The earlier version held the box with a weld
    while the run used a different weld, and the two disagreed: a candidate
    that scored 5/5 steady here collapsed to 3/5 in the run.
    """
    data = mujoco.MjData(model)
    mujoco.mj_resetData(model, data)
    mujoco.mj_forward(model, data)
    base = data.qpos[:7].copy()
    for e in ("box_stand", "box_hold"):
        i = mujoco.mj_name2id(model, mujoco.mjtObj.mjOBJ_EQUALITY, e)
        if i >= 0:
            data.eq_active[i] = 0
    jid = mujoco.mj_name2id(model, mujoco.mjtObj.mjOBJ_JOINT, "box_free")
    bq = int(model.jnt_qposadr[jid])
    bdof = int(model.jnt_dofadr[jid])
    bhome = data.qpos[bq:bq + 7].copy()
    n = int(seconds / model.opt.timestep)
    tail = max(1, n // 5)
    acc = np.zeros(len(PATCHES))
    mins = np.full(len(PATCHES), np.inf)
    for i in range(n):
        data.ctrl[:] = rig.pd(data, target)
        mujoco.mj_step(model, data)
        data.qpos[:7] = base
        data.qvel[:6] = 0.
        data.qpos[bq:bq + 7] = bhome
        data.qvel[bdof:bdof + 6] = 0.
        if i >= n - tail:
            v = data.sensordata[rig.touch_adr]
            acc += v
            mins = np.minimum(mins, v)
    got = data.qpos[rig.qadr]
    err = float(np.max(np.abs((target - got)[rig.arm_act])))
    return acc / tail, mins, err


