def ease(x):
    x = min(max(x, 0.), 1.)
    return .5 - .5 * math.cos(math.pi * x)


def lerp(a, b, k):
    return a + (b - a) * k


class Rig:
    """Joint bookkeeping, the PD controller, and the pad sensor zones."""

    def __init__(self, model):
        self.model = model
        self.names, qadr, vadr, kp, kd, tmax = [], [], [], [], [], []
        for a in range(model.nu):
            j = model.actuator_trnid[a, 0]
            n = mujoco.mj_id2name(model, mujoco.mjtObj.mjOBJ_JOINT, j)
            self.names.append(n)
            qadr.append(model.jnt_qposadr[j])
            vadr.append(model.jnt_dofadr[j])
            gp, gd = 60., 2.
            for key, a_, b_ in GAINS:
                if key in n:
                    gp, gd = a_, b_
                    break
            kp.append(gp)
            kd.append(gd)
            tmax.append(model.actuator_ctrlrange[a, 1])
        self.qadr = np.array(qadr); self.vadr = np.array(vadr)
        self.kp = np.array(kp); self.kd = np.array(kd)
        self.tmax = np.array(tmax)
        self.nu = model.nu

        self.limit = {}
        for a, n in enumerate(self.names):
            j = model.actuator_trnid[a, 0]
            if model.jnt_limited[j]:
                self.limit[n] = (float(model.jnt_range[j][0]),
                                 float(model.jnt_range[j][1]))

        self.touch_adr, self.site_id = [], []
        self.site_type, self.site_size = [], []
        for p in PATCHES:
            s = mujoco.mj_name2id(model, mujoco.mjtObj.mjOBJ_SENSOR,
                                  f"touch_{p}")
            sid = mujoco.mj_name2id(model, mujoco.mjtObj.mjOBJ_SITE,
                                    f"bubble_{p}")
            if s < 0 or sid < 0:
                raise SystemExit(
                    f"touch_{p} / bubble_{p} missing from the model.\n"
                    f"Run:  python step9_place_sites.py")
            self.touch_adr.append(int(model.sensor_adr[s]))
            self.site_id.append(sid)
            self.site_type.append(int(model.site_type[sid]))
            self.site_size.append(np.array(model.site_size[sid], dtype=float))
        self.touch_adr = np.array(self.touch_adr)
        self.live_idx = np.array([PATCHES.index(p) for p in LIVE])
        self.arm_idx = np.array([PATCHES.index(p) for p in ARM_PADS])
        # Tracking error is judged on the ARM joints alone. The legs dangle
        # because the base is pinned, so including them would reject every
        # candidate on an error that has nothing to do with the hug.
        self.arm_act = np.array([i for i, n in enumerate(self.names)
                                 if any(k in n for k in ARM_JOINTS)])

        # Bodies the wrap test needs. A hug is a statement about where the
        # elbow and the wrist are, not about how many pads light up.
        self.elbow_bid, self.wrist_bid, self.shldr_bid = {}, {}, {}
        for s in ("left", "right"):
            self.elbow_bid[s] = mujoco.mj_name2id(
                model, mujoco.mjtObj.mjOBJ_BODY, f"{s}_elbow_link")
            self.wrist_bid[s] = mujoco.mj_name2id(
                model, mujoco.mjtObj.mjOBJ_BODY, f"{s}_wrist_roll_link")
            self.shldr_bid[s] = mujoco.mj_name2id(
                model, mujoco.mjtObj.mjOBJ_BODY, f"{s}_shoulder_yaw_link")

    def arm_frame(self, data, s):
        """(shoulder, elbow, wrist) world positions for one arm."""
        return (np.array(data.xpos[self.shldr_bid[s]], dtype=float),
                np.array(data.xpos[self.elbow_bid[s]], dtype=float),
                np.array(data.xpos[self.wrist_bid[s]], dtype=float))

    def wrap_check(self, data, cx, hx, hy, cz, hz):
        """Is this arrangement actually a hug? Returns (ok, reason).

        Counting pads is not enough. The search happily returned a pose with
        both forearms VERTICAL and the hands above the head, brushing the
        box's front face on the way up: six pads lit, and it looked nothing
        like an embrace. These are the things that make it one.
        """
        front, top, bot = cx + hx, cz + hz, cz - hz
        # The forearm has to cross the box's MIDDLE, not ride its top edge.
        # The previous tolerance let the wrist sit 35 mm above the lid and
        # still pass: both forearms ended up lying across the top of the box
        # like crossed arms, the lower-arm pads grazed the lid by 2 mm, and
        # they reported 0.00 N for the entire carry.
        band = 0.15 * (top - bot)
        for s in ("left", "right"):
            sh, el, wr = self.arm_frame(data, s)
            if wr[2] > sh[2] + 0.05:
                return False, "hand above the shoulder"
            if el[2] > top:
                return False, "elbow above the lid"
            u = wr - el
            n = float(np.linalg.norm(u))
            if n < 1e-6 or abs(u[2]) / n > 0.50:
                return False, "forearm not horizontal"
            if not (bot + band <= wr[2] <= top - band):
                return False, "wrist on the lid or under the base, not across"
            if wr[0] < front - 0.02:
                return False, "wrist never reached the front face"
            if abs(wr[1]) > hy - 0.03:
                return False, "wrist outside the box width, not in front"
            if abs(el[1]) < hy - 0.03:
                return False, "elbow pulled in front instead of staying out"
            if el[0] > front - 0.03:
                return False, "elbow level with the front face, not beside"
        return True, "ok"

    def wrap_quality(self, data, cx, hx, hy, cz, hz):
        """How deep the wrap is, for ranking poses that all pass the test.

        Rewards the wrist being well past the front face and well inside the
        box's width -- i.e. genuinely round the front -- and sitting near the
        box's mid-height rather than at an edge.
        """
        front = cx + hx
        q = 0.
        for s in ("left", "right"):
            _, el, wr = self.arm_frame(data, s)
            q += max(0., float(wr[0]) - front)            # past the front
            q += max(0., hy - abs(float(wr[1]))) * 0.5    # inside the width
            q -= abs(float(wr[2]) - cz) * 0.5             # near mid-height
            q += max(0., abs(float(el[1])) - hy) * 0.5    # elbow outside
        return q

    # ---- pose ----------------------------------------------------------
    def pose(self, pitch, roll, yaw, elbow):
        """Mirrored arm pose. roll and yaw are mirrored, pitch and elbow are
        not: both of those swing in the sagittal plane, which is the same
        direction for both arms."""
        q = np.zeros(self.nu)
        for side, s in (("left", 1.), ("right", -1.)):
            for joint, v in zip(ARM_JOINTS,
                                (pitch, s * roll, s * yaw, elbow)):
                jn = f"{side}_{joint}_joint"
                if jn in self.names:
                    lo, hi = self.limit.get(jn, (-9e9, 9e9))
                    q[self.names.index(jn)] = min(max(v, lo), hi)
        return q

    def clipped(self, pitch, roll, yaw, elbow):
        """True if none of the four angles had to be clipped by a limit."""
        for side, s in (("left", 1.), ("right", -1.)):
            for joint, v in zip(ARM_JOINTS,
                                (pitch, s * roll, s * yaw, elbow)):
                jn = f"{side}_{joint}_joint"
                lo, hi = self.limit.get(jn, (-9e9, 9e9))
                if not (lo - 1e-9 <= v <= hi + 1e-9):
                    return True
        return False

    def pd(self, data, target):
        tau = (self.kp * (target - data.qpos[self.qadr])
               - self.kd * data.qvel[self.vadr])
        return np.clip(tau, -self.tmax, self.tmax)

    # ---- sensor zones --------------------------------------------------
    def _inside(self, k, q):
        t, s = self.site_type[k], self.site_size[k]
        if t == mujoco.mjtGeom.mjGEOM_BOX:
            return bool(np.all(np.abs(q) <= s[:3]))
        if t == mujoco.mjtGeom.mjGEOM_SPHERE:
            return float(np.linalg.norm(q)) <= s[0]
        if t == mujoco.mjtGeom.mjGEOM_CAPSULE:
            z = min(max(float(q[2]), -s[1]), s[1])
            return float(np.linalg.norm(q - np.array([0., 0., z]))) <= s[0]
        if t == mujoco.mjtGeom.mjGEOM_ELLIPSOID:
            return float(np.sum((q / s[:3]) ** 2)) <= 1.0
        if t == mujoco.mjtGeom.mjGEOM_CYLINDER:
            return abs(float(q[2])) <= s[1] and \
                float(np.hypot(q[0], q[1])) <= s[0]
        return False

    def zone_hits(self, data, box_gid):
        """Per pad: how many box contact points land in its zone, and WHICH
        FACE of the box each of them is on.

        The face is what makes this a wrap test rather than a contact count.
        Constraining joint coordinates did not work: the search kept finding
        arrangements that satisfied the numbers while the forearms lay across
        the lid, and when the lid was ruled out by height it simply raised the
        box until the lid was at the right height. A contact point on the top
        face is a contact point on the top face wherever the box happens to
        be, so this cannot be gamed.
        """
        hits = np.zeros(len(PATCHES), dtype=int)
        faces = [set() for _ in PATCHES]
        pen = 0.
        bid = int(self.model.geom_bodyid[box_gid])
        bc = np.array(data.xpos[bid], dtype=float)
        bR = np.array(data.xmat[bid], dtype=float).reshape(3, 3)
        bs = np.maximum(np.array(self.model.geom_size[box_gid], dtype=float),
                        1e-9)
        for c in range(data.ncon):
            con = data.contact[c]
            if int(con.geom1) != box_gid and int(con.geom2) != box_gid:
                continue
            pen += max(0., -float(con.dist))
            p = np.array(con.pos, dtype=float)
            loc = bR.T @ (p - bc)
            k = int(np.argmax(np.abs(loc) / bs))
            if k == 0:
                face = "front" if loc[0] > 0 else "back"
            elif k == 1:
                face = "side"
            else:
                face = "top" if loc[2] > 0 else "bottom"
            for j, sid in enumerate(self.site_id):
                R = np.array(data.site_xmat[sid]).reshape(3, 3)
                if self._inside(j, R.T @ (p - np.array(data.site_xpos[sid]))):
                    hits[j] += 1
                    faces[j].add(face)
        return hits, pen, faces

    def face_check(self, faces):
        """Are the pads touching the faces an embrace would touch?

        chest      the box's BACK face   (it is against the body)
        upper arm  the SIDE faces        (the arms come down either side)
        lower arm  FRONT or SIDE         (the forearms close round the front)

        A forearm contact on the TOP face means the arm is resting on the
        lid, which is the failure mode every run so far has produced.
        """
        idx = {p: PATCHES.index(p) for p in PATCHES}
        f = faces[idx["chest"]]
        if f and "back" not in f:
            return False, "chest touching something other than the back face"
        for s in ("left", "right"):
            up = faces[idx[f"{s}_upper_arm"]]
            lo = faces[idx[f"{s}_lower_arm"]]
            if not up or "side" not in up:
                return False, "upper arm not on the side face"
            if "bottom" in up:
                return False, "upper arm scooping from underneath"
            if not lo:
                return False, "forearm touching nothing"
            if "front" not in lo:
                # Grazing the side face on the way past is not a wrap. The
                # last run passed with the forearms on "side" alone: they
                # clipped the front-top corner and then hung 30 mm in front
                # of the box in open air. The forearm has to end up ON the
                # front face, which is the whole point of an embrace.
                return False, "forearm not on the front face"
        return True, "ok"


