def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--dir", default=DEFAULT_DIR)
    ap.add_argument("--robot-file", default="g1_29dof_bubble.xml")
    ap.add_argument("--scene-name", default="scene_carry.xml")
