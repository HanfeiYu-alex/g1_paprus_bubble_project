    ap.add_argument("--box-height", type=float, default=0.13)
    ap.add_argument("--no-wrap-check", action="store_true",
                    help="accept any pose that lights the pads, even if the "
                         "arms are not actually wrapped around the box")
    ap.add_argument("--mass", type=float, default=2.0)
    ap.add_argument("--friction", type=float, default=1.2)
    ap.add_argument("--pose", type=float, nargs=4, default=None,
                    metavar=("PITCH", "ROLL", "YAW", "ELBOW"),
                    help="skip the search and use this pose")
    ap.add_argument("--box-z", type=float, default=None,
                    help="fix the box height instead of searching")
    ap.add_argument("--quick", action="store_true",
                    help="coarse search grid, about 4x faster")
    ap.add_argument("--finalists", type=int, default=12)
    ap.add_argument("--grasp", choices=("assisted", "physical"),
                    default="assisted")
    ap.add_argument("--lift", type=float, default=0.20)
    ap.add_argument("--travel", type=float, default=0.60)
    ap.add_argument("--duration", type=float, default=23.0)
    ap.add_argument("--headless", action="store_true")
    ap.add_argument("--log", default="carry.csv")
    args = ap.parse_args()

