    print()
    print("=" * 72)
    print("STAGE 2  real controller, real sensors")
    print("=" * 72)
    # Every finalist is tried, and the winner is the one whose WEAKEST live
    # pad carries the most force.
    #
    # Stopping at the first candidate that merely passed was the wrong rule.
    # It accepted a pose with 370 N on the chest, 220 N on each upper arm and
    # 59 N on each forearm: a real wrap, but a light one, and the forearm
    # channels looked almost dead next to the others. Candidates further down
    # the list closed the shoulder yaw harder (-0.93, -1.27 instead of -0.60)
    # and were never even tried. Maximising the weakest channel is exactly
    # the requirement -- every pad carrying real load for the whole carry --
    # expressed as something the search can optimise.
    print(f"  {'#':>3s} {'box':>16s} {'pose':>28s} {'live':>5s} "
          f"{'steady':>7s} {'weakest':>8s} {'err':>7s}")
    tried = []
    for rank, r in enumerate(results[:args.finalists], 1):
        _, live, pen, dp, w, cz, press, p, rl, y, e, q = r
        hx, hy = dp / 2., w / 2.
        cx = chest_back - press + hx
        write_scene(scene_path, args.robot_file, cx, cz, hx, hy, hz,
                    args.mass, args.friction)
        m = mujoco.MjModel.from_xml_path(scene_path)
        rig = Rig(m)
        mean, mins, err = physics_trial(m, rig, rig.pose(p, rl, y, e))
        nlive = int((mean[rig.live_idx] > TOUCH_ON).sum())
        held = int((mins[rig.live_idx] > TOUCH_ON).sum())
        weakest = float(np.min(mins[rig.live_idx]))
        ok = held == len(LIVE) and err < 0.30
