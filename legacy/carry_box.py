    rig = Rig(model)

    # ---- the open pose: it must be contact-free on the arms -------------
    probe2 = Probe(scene_path)
    probe2.resize(hx, hy, hz)
    # The open pose must differ from the wrapped one in YAW, not only in
    # roll. The previous version tried dy = 0.0 first, found that abducting
    # the shoulder alone cleared the box, and stopped there -- so open_yaw
    # equalled yaw_close, the "wrap" phase commanded no change at all, and
    # the forearms never visibly closed. Search the largest yaw swing first
    # and add only as much roll as it takes to clear the box.
    open_roll, open_yaw = roll, yaw_close
    found_open = False
    for dy in (1.00, 0.85, 0.70, 0.55, 0.40):
        for extra in np.arange(0.00, 1.35, 0.05):
            rr, yy = roll + extra, yaw_close + dy
            if rig.clipped(pitch, rr, yy, elbow):
                continue
            hits, _, _ = probe2.hits(
                rig.pose(pitch, rr, yy, elbow), cx, cz)
            if int(hits[rig.arm_idx].sum()) == 0:
                open_roll, open_yaw, found_open = rr, yy, True
                break
        if found_open:
            break

    print()
    print("=" * 72)
    print("THE RUN")
    print("=" * 72)
    print(f"box   {dp:.2f} deep x {w:.2f} wide x {height:.2f} tall, "
          f"{args.mass:.1f} kg")
    print(f"      it lies ACROSS the body: width {w:.2f} > depth {dp:.2f}, so")
    print(f"      the arms wrap a long face instead of pinching a cube")
    print(f"      back face x {back:+.3f} (pressed {press*1000:.0f} mm into "
          f"the chest), centre ({cx:+.3f}, 0, {cz:.2f})")
    print(f"hug   pitch {pitch:+.2f} ({math.degrees(-pitch):.0f} deg of "
          f"shoulder flexion)  roll {roll:+.2f}  elbow {elbow:+.2f}")
    print(f"      forearms swing on shoulder yaw {open_yaw:+.2f} -> "
          f"{yaw_close:+.2f}")
    print(f"open  roll {open_roll:+.2f}" +
          ("  (arms clear of the box)" if found_open else
           "  WARNING: could not find a contact-free open pose"))

    # Where the arms actually end up, in plain numbers, so the shape of the
    # hug can be checked without squinting at the viewer.
    probe2.place(rig.pose(pitch, roll, yaw_close, elbow), cx, cz)
    front, top, bot = cx + hx, cz + hz, cz - hz
    print(f"\n  box front face x {front:+.3f}, sides y +-{hy:.3f}, "
          f"z {bot:.3f}..{top:.3f}")
    print(f"  {'':10s} {'shoulder':>24s} {'elbow':>24s} {'wrist':>24s}")
    for s in ("left", "right"):
        sh, el, wr = rig.arm_frame(probe2.data, s)
        f = lambda v: f"({v[0]:+.3f},{v[1]:+.3f},{v[2]:+.3f})"
        print(f"  {s:10s} {f(sh):>24s} {f(el):>24s} {f(wr):>24s}")
    wh, _, wfaces = probe2.hits(rig.pose(pitch, roll, yaw_close, elbow),
                                cx, cz)
    print(f"\n  which face of the box each pad is on")
    for k, pad in enumerate(PATCHES):
        f = ",".join(sorted(wfaces[k])) if wfaces[k] else "-"
        print(f"    {pad:17s} {wh[k]:3d} contacts   {f}")
    fok, fwhy = rig.face_check(wfaces)
    ok, why = rig.wrap_check(probe2.data, cx, hx, hy, cz, hz)
    print(f"  face test: {'PASS' if fok else 'FAIL - ' + fwhy}")
    print(f"  wrap test: {'PASS' if ok else 'FAIL - ' + why}")
    print("  (an embrace means: chest on the BACK face, upper arms on the")
    print("   SIDE faces, forearms on FRONT or SIDE. A forearm on TOP is an")
    print("   arm resting on the lid.)")
    print(f"  (a hug means elbows OUT at |y| >= {hy-0.06:.3f} beside the box,")
    print(f"   wrists IN at |y| <= {hy+0.02:.3f} and x >= {front-0.05:+.3f},")
    print(f"   i.e. round the front face, with the forearms horizontal)")

    wrapped = rig.pose(pitch, roll, yaw_close, elbow)
    embraced = rig.pose(pitch, roll, open_yaw, elbow)      # upper arms on
    opened = rig.pose(pitch, open_roll, open_yaw, elbow)   # wide, no contact
    # The start pose has to be clear of the box too. The previous run opened
    # with a 7898 N spike because the arms hang straight down through the
    # space the box occupies, so frame zero began fully penetrated.
    rest = rig.pose(pitch * 0.25, open_roll, open_yaw, elbow * 0.3)
    rest_hits, _, _ = probe2.hits(rest, cx, cz)
    if int(rest_hits[rig.arm_idx].sum()) > 0:
        rest = opened

    data = mujoco.MjData(model)
    mujoco.mj_resetData(model, data)
    mujoco.mj_forward(model, data)
    base = data.qpos[:7].copy()
    box_bid = mujoco.mj_name2id(model, mujoco.mjtObj.mjOBJ_BODY, "box")
    stand = mujoco.mj_name2id(model, mujoco.mjtObj.mjOBJ_EQUALITY, "box_stand")
    hold = mujoco.mj_name2id(model, mujoco.mjtObj.mjOBJ_EQUALITY, "box_hold")
    z0 = float(data.xpos[box_bid][2]); x0 = float(data.xpos[box_bid][0])

    # In assisted mode the box is held KINEMATICALLY, not by a weld.
    #
    # A weld records the relative pose it has to maintain when the MODEL is
    # compiled. By the time box_hold switched on, the arms had pushed the box
    # 7 mm forward, so the weld yanked it back 7 mm in one step. The forearms
    # were pressing on the front face, that face retreated out from under
    # them, and the contact broke: forearm force went 117 N -> 0 N in a
    # single phase, the arms lost the resistance they had been pushing
    # against, and the PD controller flung them to the commanded pose. That
    # is the "hands were right, then they got thrown up" in the viewer.
    #
    # Pinning the box the way the base is pinned -- set its qpos every step
    # -- removes the drift, the snap-back and the two-welds-fighting problem
    # in one go. The box travels in exact lockstep with the robot and the
    # touch sensors report the genuine squeeze from the arms.
    box_jid = mujoco.mj_name2id(model, mujoco.mjtObj.mjOBJ_JOINT, "box_free")
    box_q = int(model.jnt_qposadr[box_jid])
    box_dof = int(model.jnt_dofadr[box_jid])
    box_home = data.qpos[box_q:box_q + 7].copy()
    assisted = args.grasp == "assisted"

    # The verdict is about the CARRY. Measuring from the start of the grip
    # counted the ramp in which the forearm contact is still closing, and
    # reported a steady hold as a dropout because one early frame read zero.
    HOLD_PHASES = ("lift", "carry", "place")

    def sched(t):
        """phase, arm target, (dx, dz) of the base, stand weld, hold weld"""
        a = args.grasp == "assisted"
        if t < 1.0:
            return "approach", rest, (0., 0.), True, False
        if t < 3.0:
            k = ease((t - 1.0) / 2.0)
            return "open", lerp(rest, opened, k), (0., 0.), True, False
        if t < 5.0:
            # Pitch and roll reach their hug values. The UPPER arms come down
            # onto the box's two long side faces here.
            k = ease((t - 3.0) / 2.0)
            return "embrace", lerp(opened, embraced, k), (0., 0.), True, False
        if t < 7.5:
            # Pitch and roll are frozen. Only shoulder yaw moves, which curls
            # the FOREARMS in around the front face. This is the hug.
            k = ease((t - 5.0) / 2.5)
            return "wrap", lerp(embraced, wrapped, k), (0., 0.), True, False
        if t < 9.3:
            # The squeeze settles with the box still on its stand, and the
            # torso weld stays OFF. Leaving both welds on for two seconds
            # put two rigid constraints on one body: they fought, and the
            # fight is most of the 2000 N that appeared on the chest.
            return "grip", wrapped, (0., 0.), True, False
        if t < 9.5:
            return "grip", wrapped, (0., 0.), True, a   # 0.2 s handover
        if t < 10.5:
            return "release", wrapped, (0., 0.), False, a
        if t < 13.0:
            k = ease((t - 10.5) / 2.5)
            return "lift", wrapped, (0., args.lift * k), False, a
        if t < 18.0:
            k = ease((t - 13.0) / 5.0)
            return "carry", wrapped, (args.travel * k, args.lift), False, a
        if t < 20.5:
            k = ease((t - 18.0) / 2.5)
            return ("place", wrapped, (args.travel, args.lift * (1 - k)),
                    False, a)
        return "let go", opened, (args.travel, 0.), False, False

    log = open(args.log, "w", buffering=1) if args.log else None
    if log:
        log.write("t,phase,held," + ",".join(PATCHES)
                  + ",total_N,n_live,box_x,box_z\n")

    spf = max(1, int((1 / 60) / model.opt.timestep))
    peak, last = 1., -1.
    phase_force, phase_live = {}, {}
    seen = {p: 0. for p in PATCHES}
    hold_min = {p: float("inf") for p in PATCHES}
    hold_samples = 0
    carry_top = z0
    viewer = None
    if not args.headless:
        # launch_passive, not the context manager: exiting the context
        # manager after the loop was segfaulting on teardown.
        viewer = mujoco.viewer.launch_passive(model, data)
    w0 = time.time()
    try:
        while data.time < args.duration:
            if viewer is not None and not viewer.is_running():
                break
            for _ in range(spf):
                phase, tgt, (dx, dz), on_stand, on_hold = sched(data.time)
                data.ctrl[:] = rig.pd(data, tgt)
                if assisted:
                    data.eq_active[stand] = 0
                    data.eq_active[hold] = 0
                else:
                    data.eq_active[stand] = 1 if on_stand else 0
                    data.eq_active[hold] = 0
                mujoco.mj_step(model, data)
                pin = base.copy(); pin[0] += dx; pin[2] += dz
                data.qpos[:7] = pin
                data.qvel[:6] = 0.
                if assisted and (on_stand or on_hold):
                    bp = box_home.copy()
                    bp[0] += dx
                    bp[2] += dz
                    data.qpos[box_q:box_q + 7] = bp
                    data.qvel[box_dof:box_dof + 6] = 0.
            v = data.sensordata[rig.touch_adr].copy()
            tot = float(v.sum())
            nlive = int((v[rig.live_idx] > TOUCH_ON).sum())
            bx = float(data.xpos[box_bid][0]); bz = float(data.xpos[box_bid][2])
            peak = max(peak, float(v.max()))
            phase_force[phase] = max(phase_force.get(phase, 0.), tot)
            phase_live[phase] = max(phase_live.get(phase, 0), nlive)
            for p, x in zip(PATCHES, v):
                seen[p] = max(seen[p], float(x))
            if phase in HOLD_PHASES:
                hold_samples += 1
                for p, x in zip(PATCHES, v):
                    hold_min[p] = min(hold_min[p], float(x))
            if phase in ("lift", "carry", "place"):
                carry_top = max(carry_top, bz)
            if viewer is not None:
                viewer.sync()
            if data.time - last >= 1.0:
                last = data.time
                tag = "stand" if on_stand else ("torso" if on_hold else "FREE")
                print(f"t={data.time:5.1f}s [{phase:8s}] {tag:5s} "
                      f"{tot:7.2f} N  {nlive}/5  box ({bx:+.3f}, {bz:.3f})")
                for p, x in zip(PATCHES, v):
                    k = 0 if peak <= 0 else int(round(16 * min(x / peak, 1.)))
                    print(f"    {p:17s} |{'#'*k}{'.'*(16-k)}| {x:7.2f} N")
            if log:
                log.write(f"{data.time:.4f},{phase},"
                          f"{int(on_hold or on_stand)},"
                          + ",".join(f"{x:.4f}" for x in v)
                          + f",{tot:.4f},{nlive},{bx:.5f},{bz:.5f}\n")
            if viewer is not None:
                lag = data.time - (time.time() - w0)
                if lag > 0:
                    time.sleep(lag)
    finally:
        if viewer is not None:
            try:
                viewer.close()
            except Exception:
                pass
        if log:
            log.close()

    # ---- the verdict ----------------------------------------------------
    bx = float(data.xpos[box_bid][0]); bz = float(data.xpos[box_bid][2])
    print("\n" + "=" * 72)
    print("RESULT")
    print("=" * 72)
    print(f"  {'phase':10s} {'peak force':>12s} {'x weight':>10s} "
          f"{'live pads':>11s}")
    for k in ("approach", "open", "embrace", "wrap", "grip", "release",
              "lift", "carry", "place", "let go"):
        if k in phase_force:
            print(f"  {k:10s} {phase_force[k]:12.2f} "
                  f"{phase_force[k]/weight:10.1f} {phase_live[k]:10d}/5")
    travelled = bx - x0
    print(f"\n  box started at x {x0:+.3f}, z {z0:.3f}")
    print(f"  box ended   at x {bx:+.3f}, z {bz:.3f}")
    print(f"  travelled {travelled:+.3f} m (commanded {args.travel:+.3f})")
    print(f"  highest the box reached: z {carry_top:.3f}")
    carried = (travelled > 0.6 * args.travel
               and carry_top > z0 + 0.5 * args.lift)

    print(f"\n  pads during the lift and carry ({hold_samples} samples)")
    print(f"  {'pad':17s} {'min N':>9s} {'peak N':>9s}   verdict")
    all_held = True
    for p in PATCHES:
        lo = 0. if hold_min[p] == float("inf") else hold_min[p]
        if p == "back":
            verdict = ("silent, as expected" if seen[p] <= TOUCH_ON
                       else "unexpectedly touched")
        elif lo > TOUCH_ON:
            verdict = "data for the whole carry"
        elif seen[p] > TOUCH_ON:
            verdict = "touched, but dropped out"
            all_held = False
        else:
            verdict = "NEVER TOUCHED"
            all_held = False
        print(f"  {p:17s} {lo:9.2f} {seen[p]:9.2f}   {verdict}")

    print()
    if carried and all_held:
        print("  PASS. The box was hugged and carried, and all five live pads")
        print("  reported force continuously from grip through place. That is")
        print("  what 'completely wrapped' looks like in the data.")
    elif carried:
        print("  Carried, but not every live pad held. The ones marked above")
        print("  are where the wrap is loose.")
        bad = [p for p in LIVE if hold_min[p] <= TOUCH_ON]
        if any("lower_arm" in p for p in bad):
            print("    forearms dropping out: the box sags when box_stand is")
            print("    released. Try --box 0.12 0.36 0.20 to let the")
            print("    forearms reach further round the front face.")
        if "chest" in bad:
            print("    chest dropping out: increase the press with")
            print("    --box 0.13 0.36 0.20 and re-run, or thicken the pad")
            print("    with step9_place_sites.py --pad-thick 0.05")
    elif carry_top < z0 + 0.05:
        print("  Did not lift. In physical mode that is the grip's real")
        print("  limit; in assisted mode it means the weld never engaged.")
    else:
        print("  Lifted but did not travel as commanded.")

    print(f"\n  tactile log: {args.log}")
    print(f"  columns: t, phase, held, {len(PATCHES)} channels "
          f"({', '.join(PATCHES)}), total, live count, box x, box z")

    if viewer is not None:
        # MuJoCo's passive viewer segfaults while tearing its GL context
        # down under WSLg. Everything above is already written and flushed,
        # so leave by the front door instead of letting the crash be the
        # last thing printed.
        sys.stdout.flush()
        os._exit(0)


