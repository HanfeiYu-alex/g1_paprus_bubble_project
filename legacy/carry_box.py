# Channel order, fixed. Must match step9_place_sites.py.
PATCHES = ["chest", "back",
           "left_upper_arm", "left_lower_arm",
           "right_upper_arm", "right_lower_arm"]
# The pads that must have data for the whole carry. The back pad is not one
# of them: there is nothing behind the robot to touch it.
LIVE = ["chest",
        "left_upper_arm", "left_lower_arm",
        "right_upper_arm", "right_lower_arm"]
ARM_PADS = ["left_upper_arm", "left_lower_arm",
            "right_upper_arm", "right_lower_arm"]

ARM_JOINTS = ("shoulder_pitch", "shoulder_roll", "shoulder_yaw", "elbow")
GAINS = [("hip", 150., 5.), ("knee", 200., 8.), ("ankle", 60., 3.),
         ("waist", 150., 5.), ("shoulder", 140., 5.0), ("elbow", 110., 3.5),
         ("wrist", 20., 1.)]
