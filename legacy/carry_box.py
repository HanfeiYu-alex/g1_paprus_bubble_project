"""A complete hug-and-carry run for the G1, with six bubble channels logged.

What is different from the last version, and why.

1. SIX pads, not eight. The real hardware has one large bubble on the chest,
   one on the back, and one per arm segment. step9_place_sites.py now
   measures the torso's collision envelope and lays the chest and back pads
   straddling the real surface. The old chest sites were 5 cm in front of
   the surface they were supposed to be mounted on, which is why that
   channel read 0.00 N in every run.

2. The box lies ACROSS the body. Width (y) is much larger than depth (x), so
   the arms wrap around a long face instead of pinching a cube. Depth is
   kept small so the forearms can reach past the front face.

3. The pose is SEARCHED, not guessed. Every earlier search swept shoulder
   pitch over -0.55..-0.25 rad, which is 14 to 31 degrees of forward flexion.
   Nobody hugs anything with their shoulders at 20 degrees: it takes 70 to
   90, i.e. pitch near -1.3. The arms stayed "straight down at the sides" in
   every run because the search space never contained a hug. This version
   sweeps pitch to -1.75 and the elbow to -1.6 (negative is flexion), in two
   stages:

     stage 1  geometric. Set the joints directly, run mj_forward, and test
              every box contact point against every pad's sensor zone, using
              the same point-in-zone rule MuJoCo's touch sensor uses. About
              half a millisecond per candidate, so tens of thousands of
              candidates are affordable.
     stage 2  physical. Take the finalists, drive them with the real PD
              controller against gravity, and read the real sensors. A pose
              that stage 1 likes but the controller cannot hold is rejected
              here.

   A candidate is only accepted when all FIVE live pads (everything except
   the back) report force. The back pad is expected to stay silent: nothing
   is behind the robot.

4. The motion is staged so the hug is visible:

     approach  arms down and clear
     open      abduct and lift, arms wide, zero contact
     embrace   pitch and roll reach their final values -- the UPPER arms
               land on the box's two long side faces
     wrap      pitch and roll FROZEN, shoulder yaw alone swings the
               FOREARMS in around the front face
     grip / lift / carry / place / let go

    python carry_box.py
    python carry_box.py --quick            # coarse search, faster
    python carry_box.py --headless --log run.csv
    python carry_box.py --mass 4.0 --log heavy.csv
"""

