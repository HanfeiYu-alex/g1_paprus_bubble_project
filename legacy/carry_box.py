        # sides and the embrace has nothing to close against.
        # Depth is what the last run got wrong. With the back face on the
        # chest at x 0.076 and a depth of 0.14, the front face sat at 0.202
        # while the wrapped forearm crossed into the box's width at x 0.197
        # and reached x 0.238 -- it left the box through the front corner
