    ap.add_argument("--headless", action="store_true")
    ap.add_argument("--video", default=None,
                    help="render offscreen to this .mp4 instead of relying "
                         "on the interactive window. Run it as "
                         "MUJOCO_GL=egl python hug_walk.py --video run.mp4")
    ap.add_argument("--video-fps", type=int, default=30)
