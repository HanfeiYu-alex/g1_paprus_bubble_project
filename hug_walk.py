"""Hug a box with the chest and both arms, then walk with it.

This joins the two halves of the project:

  the posture work  -- six bubble pads, a two-stage search for an embrace
                       that loads all of them, and face-based tests that
                       tell a hug apart from an arm resting on the lid
  the walking work  -- OpenHomie's ONNX policy driving the legs at 50 Hz
                       while the arms hold whatever pose they are given

Why the integration has to happen on OpenHomie's model, not ours:

  The policy's input width is baked into the ONNX file at 456 = 6 x 76,
  and 76 = 10 + 2*27 + 12. It only accepts a 27-joint robot. Our posture
  work was done on unitree_mujoco's 29-DOF G1. The policy cannot move; the
  pads and the search can, so they did. Every body and joint name our code
  needs exists in OpenHomie's g1.xml, and the torso envelope and arm
  segment lengths measured there are the same to a millimetre, so the
  geometry carries over unchanged.

Three things about that model are easy to get wrong:

  1. Every actuator has ctrlrange 0. Our old PD clipped torque to
     actuator_ctrlrange, which on this model clips every torque to ZERO and
     the robot simply collapses. Torque is not clipped here.
  2. The shoulder sits at z 1.085 with the legs straight, but the policy
     walks in a slight squat, so the shoulder is lower in motion. The grasp
     is therefore defined in the TORSO frame, not the world frame, and the
     geometry holds at any base height.
  3. The box must be held relative to the torso both before and after the
     grasp, or the hug the search found is not the hug the run executes.

    python hug_walk.py                      # search, then walk
    python hug_walk.py --quick              # coarse search
    python hug_walk.py --pose -0.9 0.35 -0.6 0.1    # skip the search
    python hug_walk.py --headless --log run.csv
"""

