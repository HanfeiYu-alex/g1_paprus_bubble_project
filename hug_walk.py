class Rig:
    """Index bookkeeping, the arm PD, and the bubble pads."""

    def __init__(self, model):
        self.model = model
        self.nj = int(model.nu)                 # 27 actuated joints
        self.qstart = 7                         # after the floating base
        self.vstart = 6

        self.act_of_joint = {}
        for a in range(model.nu):
            j = int(model.actuator_trnid[a, 0])
            n = mujoco.mj_id2name(model, mujoco.mjtObj.mjOBJ_JOINT, j)
            self.act_of_joint[n] = a
        self.limit = {}
        for n, a in self.act_of_joint.items():
            j = int(model.actuator_trnid[a, 0])
            if model.jnt_limited[j]:
                self.limit[n] = (float(model.jnt_range[j][0]),
                                 float(model.jnt_range[j][1]))

        # ctrl[12:] is driven by a 15-long "upper body" vector: waist_yaw
        # plus seven joints per arm. Indices are read from the model rather
        # than hard-coded, so a different joint order cannot silently
        # scramble the pose.
        self.upper0 = 12
        self.n_upper = self.nj - self.upper0
        self.upper_of = {}
        for n, a in self.act_of_joint.items():
            if a >= self.upper0:
                self.upper_of[n] = a - self.upper0

        self.box_gid = mujoco.mj_name2id(model, mujoco.mjtObj.mjOBJ_GEOM,
                                         "box_geom")
        self.box_bid = mujoco.mj_name2id(model, mujoco.mjtObj.mjOBJ_BODY,
                                         "box")
        jid = mujoco.mj_name2id(model, mujoco.mjtObj.mjOBJ_JOINT, "box_free")
        self.box_q = int(model.jnt_qposadr[jid])
        self.box_dof = int(model.jnt_dofadr[jid])
        self.torso_bid = mujoco.mj_name2id(model, mujoco.mjtObj.mjOBJ_BODY,
                                           "torso_link")

        self.touch_adr, self.site_id = [], []
        self.site_type, self.site_size = [], []
        for p in PATCHES:
            s = mujoco.mj_name2id(model, mujoco.mjtObj.mjOBJ_SENSOR,
                                  f"touch_{p}")
            sid = mujoco.mj_name2id(model, mujoco.mjtObj.mjOBJ_SITE,
                                    f"bubble_{p}")
            if s < 0 or sid < 0:
                raise SystemExit(
                    f"touch_{p} / bubble_{p} missing.\n"
                    f"Run step9_place_sites.py on g1.xml first -- see the "
                    f"instructions at the bottom of this error.\n"
                    f"  python step9_place_sites.py --dir {ROBOT_DIR} "
                    f"--source g1.xml --out g1_bubble.xml")
            self.touch_adr.append(int(model.sensor_adr[s]))
            self.site_id.append(sid)
            self.site_type.append(int(model.site_type[sid]))
            self.site_size.append(np.array(model.site_size[sid], dtype=float))
        self.touch_adr = np.array(self.touch_adr)
        self.live_idx = np.array([PATCHES.index(p) for p in LIVE])
        self.arm_idx = np.array([PATCHES.index(p) for p in ARM_PADS])

        self.elbow_bid, self.wrist_bid, self.shldr_bid = {}, {}, {}
        for s in ("left", "right"):
            self.elbow_bid[s] = mujoco.mj_name2id(
                model, mujoco.mjtObj.mjOBJ_BODY, f"{s}_elbow_link")
            self.wrist_bid[s] = mujoco.mj_name2id(
                model, mujoco.mjtObj.mjOBJ_BODY, f"{s}_wrist_roll_link")
            self.shldr_bid[s] = mujoco.mj_name2id(
                model, mujoco.mjtObj.mjOBJ_BODY, f"{s}_shoulder_pitch_link")

    # ---- poses ---------------------------------------------------------
    def upper(self, pitch, roll, yaw, elbow):
        """The 15-long upper-body vector for a mirrored arm pose."""
        q = np.zeros(self.n_upper)
        for side, s in (("left", 1.), ("right", -1.)):
            for joint, v in zip(ARM_JOINTS,
                                (pitch, s * roll, s * yaw, elbow)):
                jn = f"{side}_{joint}_joint"
                if jn in self.upper_of:
                    lo, hi = self.limit.get(jn, (-9e9, 9e9))
                    q[self.upper_of[jn]] = min(max(v, lo), hi)
        return q

    def clipped(self, pitch, roll, yaw, elbow):
        for side, s in (("left", 1.), ("right", -1.)):
            for joint, v in zip(ARM_JOINTS,
                                (pitch, s * roll, s * yaw, elbow)):
                lo, hi = self.limit.get(f"{side}_{joint}_joint",
                                        (-9e9, 9e9))
                if not (lo - 1e-9 <= v <= hi + 1e-9):
                    return True
        return False

    def full_q(self, upper, legs=None):
        """A whole 27-vector of joint targets."""
        q = np.zeros(self.nj)
        q[:12] = LEG_DEFAULT if legs is None else legs
        q[self.upper0:] = upper
        return q

    # ---- sensor zones --------------------------------------------------
    def _inside(self, k, q):
        t, s = self.site_type[k], self.site_size[k]
        if t == mujoco.mjtGeom.mjGEOM_BOX:
            return bool(np.all(np.abs(q) <= s[:3]))
        if t == mujoco.mjtGeom.mjGEOM_SPHERE:
            return float(np.linalg.norm(q)) <= s[0]
        if t == mujoco.mjtGeom.mjGEOM_CAPSULE:
            z = min(max(float(q[2]), -s[1]), s[1])
            return float(np.linalg.norm(q - np.array([0., 0., z]))) <= s[0]
        if t == mujoco.mjtGeom.mjGEOM_CYLINDER:
            return abs(float(q[2])) <= s[1] and \
                float(np.hypot(q[0], q[1])) <= s[0]
        return False

    def zone_hits(self, data):
        """Per pad: contact count and which box FACE each contact is on."""
        hits = np.zeros(len(PATCHES), dtype=int)
        faces = [set() for _ in PATCHES]
        pen = 0.
        bc = np.array(data.xpos[self.box_bid], dtype=float)
        bR = np.array(data.xmat[self.box_bid], dtype=float).reshape(3, 3)
        bs = np.maximum(
            np.array(self.model.geom_size[self.box_gid], dtype=float), 1e-9)
        for c in range(data.ncon):
            con = data.contact[c]
            if int(con.geom1) != self.box_gid and \
               int(con.geom2) != self.box_gid:
                continue
            pen += max(0., -float(con.dist))
            p = np.array(con.pos, dtype=float)
            loc = bR.T @ (p - bc)
            r = np.abs(loc) / bs
            mx = float(r.max())
            here = set()
            if mx > 0:
                if r[0] >= 0.85 * mx:
                    here.add("front" if loc[0] > 0 else "back")
                if r[1] >= 0.85 * mx:
                    here.add("side")
                if r[2] >= 0.85 * mx:
                    here.add("top" if loc[2] > 0 else "bottom")
            for j, sid in enumerate(self.site_id):
                R = np.array(data.site_xmat[sid]).reshape(3, 3)
                if self._inside(j, R.T @ (p - np.array(data.site_xpos[sid]))):
                    hits[j] += 1
                    faces[j] |= here
        return hits, pen, faces

    def face_check(self, faces):
        idx = {p: PATCHES.index(p) for p in PATCHES}

        def names(f):
            return "/".join(sorted(f)) if f else "nothing"
        f = faces[idx["chest"]]
        if f and "back" not in f:
            return False, f"chest on {names(f)}, not the back face"
        for s in ("left", "right"):
            up = faces[idx[f"{s}_upper_arm"]]
            lo = faces[idx[f"{s}_lower_arm"]]
            if not up or "side" not in up:
                return False, f"upper arm on {names(up)}, not the side face"
            if "bottom" in up:
                return False, "upper arm scooping from underneath"
            if not lo:
                return False, "forearm touching nothing"
            if "front" not in lo:
                return False, f"forearm on {names(lo)}, not the front face"
        return True, "ok"

    def arm_frame(self, data, s):
        return (np.array(data.xpos[self.shldr_bid[s]], dtype=float),
                np.array(data.xpos[self.elbow_bid[s]], dtype=float),
                np.array(data.xpos[self.wrist_bid[s]], dtype=float))

    def wrap_check(self, data, hx, hy, hz):
        """A hug, stated in the BOX's own frame so it holds at any base
        height: elbows outside the side faces, wrists round the front at
        mid-height, forearms horizontal, hands no higher than the
        shoulders."""
        bc = np.array(data.xpos[self.box_bid], dtype=float)
        bR = np.array(data.xmat[self.box_bid], dtype=float).reshape(3, 3)
        band = 0.30 * hz
        for s in ("left", "right"):
            sh, el, wr = self.arm_frame(data, s)
            if wr[2] > sh[2] + 0.05:
                return False, "hand above the shoulder"
            u = wr - el
            n = float(np.linalg.norm(u))
            if n < 1e-6 or abs(u[2]) / n > 0.50:
                return False, "forearm not horizontal"
            e = bR.T @ (el - bc)
            w = bR.T @ (wr - bc)
            if e[2] > hz:
                return False, "elbow above the lid"
            if not (-hz + band <= w[2] <= hz - band):
                return False, "wrist on the lid or under the base"
            if w[0] < hx - 0.02:
                return False, "wrist never reached the front face"
            if abs(w[1]) > hy - 0.03:
                return False, "wrist outside the box width, not in front"
            if abs(e[1]) < hy - 0.03:
                return False, "elbow pulled in front instead of staying out"
            if e[0] > hx - 0.03:
                return False, "elbow level with the front face, not beside"
        return True, "ok"

    def wrap_quality(self, data, hx, hy, hz):
        bc = np.array(data.xpos[self.box_bid], dtype=float)
        bR = np.array(data.xmat[self.box_bid], dtype=float).reshape(3, 3)
        q = 0.
        for s in ("left", "right"):
            _, el, wr = self.arm_frame(data, s)
            e = bR.T @ (el - bc)
            w = bR.T @ (wr - bc)
            q += max(0., float(w[0]) - hx)
            q += max(0., hy - abs(float(w[1]))) * 0.5
            q -= abs(float(w[2])) * 0.5
            # The elbow used to earn points for sitting FURTHER outside the
            # box, which quietly rewarded abduction -- swinging the whole
            # arm away from the side face it is supposed to be pressing on.
            # Being beside the box rather than in front of it is already a
            # hard requirement in wrap_check; it does not also need a prize.
        return q

    # ---- placing the box relative to the torso --------------------------
    def torso_frame(self, data):
        return (np.array(data.xpos[self.torso_bid], dtype=float),
                np.array(data.xmat[self.torso_bid],
                         dtype=float).reshape(3, 3))

    def put_box(self, data, offset):
        """Park the box at `offset` in the torso's frame, zero velocity."""
        p, R = self.torso_frame(data)
        pos = p + R @ np.asarray(offset, dtype=float)
        quat = np.zeros(4)
        mujoco.mju_mat2Quat(quat, np.array(data.xmat[self.torso_bid]))
        data.qpos[self.box_q:self.box_q + 3] = pos
        data.qpos[self.box_q + 3:self.box_q + 7] = quat
        data.qvel[self.box_dof:self.box_dof + 6] = 0.


