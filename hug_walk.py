class Robot:
    """The policy-driven legs plus PD-held arms."""

    def __init__(self, xml, policy_path, arm_kp=ARM_KP, arm_kd=ARM_KD,
                 mask_arm_obs=True):
        import onnxruntime as ort
        self.arm_kp, self.arm_kd = arm_kp, arm_kd
        self.mask_arm_obs = mask_arm_obs
        self.m = mujoco.MjModel.from_xml_path(xml)
        self.m.opt.timestep = SIM_DT
        self.d = mujoco.MjData(self.m)
        self.rig = Rig(self.m)
        self.n = self.rig.nj
        self.defaults = np.zeros(self.n, dtype=np.float32)
        self.defaults[:12] = LEG_DEFAULT
        self.policy = ort.InferenceSession(policy_path)
        self.cmd = np.zeros(3, dtype=np.float32)
        self.height = STAND_HEIGHT
        self.arm_target = np.zeros(self.rig.n_upper)
        self.step_count = 0
        self.reset_policy_state()

    def reset_policy_state(self):
        self.action = np.zeros(12, dtype=np.float32)
        self.target = LEG_DEFAULT.copy()
        obs_dim = 10 + 2 * self.n + 12
        self.hist = collections.deque(
            [np.zeros(obs_dim, np.float32)] * HISTORY, maxlen=HISTORY)

    def observation(self):
        d = self.d
        q = d.qpos[7:7 + self.n] - self.defaults
        qd = d.qvel[6:6 + self.n] * DOF_VEL_SCALE
        if self.mask_arm_obs:
            # Tell the policy the upper body is at its default and still.
            #
            # The policy was trained with the arms near zero. Feeding it a
            # hug -- shoulder pitch -1.11, elbow +0.40 -- is an input it has
            # never seen, and it answered with a self-consistent standing
            # solution and froze: cmd 0.25 went in, |act| sat at 2.49 for
            # twelve seconds, and both feet stayed planted the whole time.
            # Masking those 15 entries keeps the policy inside the
            # distribution it was trained on. The arms' real effect on
            # balance still reaches it, through the pelvis orientation and
            # angular velocity, which is the channel it learned to reject
            # disturbances on in the first place.
            q = q.copy(); qd = qd.copy()
            q[12:] = 0.
            qd[12:] = 0.
        return np.concatenate([
            self.cmd * CMD_SCALE,
            [self.height],
            d.qvel[3:6] * ANG_VEL_SCALE,
            gravity_in_body(d.qpos[3:7]),
            q, qd,
            self.action,
        ]).astype(np.float32)

    def step(self):
        d, n = self.d, self.n
        # No torque clipping. Every actuator in this model has ctrlrange 0,
        # so clipping to actuator_ctrlrange would zero every command and the
        # robot would fold up on the first step.
        d.ctrl[:12] = (self.target - d.qpos[7:19]) * LEG_KP \
            - d.qvel[6:18] * LEG_KD
        d.ctrl[12:] = (self.arm_target - d.qpos[19:7 + n]) * self.arm_kp \
            - d.qvel[18:6 + n] * self.arm_kd
        mujoco.mj_step(self.m, d)
        self.step_count += 1
        if self.step_count % DECIMATION == 0:
            self.hist.append(self.observation())
            obs = np.concatenate(self.hist)[None]
            self.action = self.policy.run(
                None, {"input": obs})[0][0].astype(np.float32)
            self.target = self.action * ACTION_SCALE + LEG_DEFAULT

    def grab(self):
        """Weld the box to the torso where it is RIGHT NOW."""
        m, d = self.m, self.d
        e = mujoco.mj_name2id(m, mujoco.mjtObj.mjOBJ_EQUALITY, "grab")
        p1 = np.array(d.xpos[self.rig.torso_bid])
        q1 = np.array(d.xquat[self.rig.torso_bid])
        p2 = np.array(d.xpos[self.rig.box_bid])
        q2 = np.array(d.xquat[self.rig.box_bid])
        q1i = np.zeros(4); mujoco.mju_negQuat(q1i, q1)
        rel_pos = np.zeros(3); mujoco.mju_rotVecQuat(rel_pos, p2 - p1, q1i)
        rel_quat = np.zeros(4); mujoco.mju_mulQuat(rel_quat, q1i, q2)
        m.eq_data[e, 3:6] = rel_pos
        m.eq_data[e, 6:10] = rel_quat
        d.eq_active[e] = 1

    def release(self):
        e = mujoco.mj_name2id(self.m, mujoco.mjtObj.mjOBJ_EQUALITY, "grab")
        self.d.eq_active[e] = 0


