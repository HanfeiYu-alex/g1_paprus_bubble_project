def write_scene(path, robot_file, cx, cz, hx, hy, hz, mass, mu,
                solref="0.02 1", solimp="0.80 0.95 0.012"):
    with open(path, "w") as fh:
        fh.write(SCENE.format(robot_file=robot_file, cx=cx, cz=cz,
                              hx=hx, hy=hy, hz=hz, mass=mass, mu=mu,
                              solref=solref, solimp=solimp))


def weld_box_to_torso(model, data, rig):
    """Weld the box to the torso where it is now.

    Holding the box with a kinematic pin instead made it an immovable wall:
    the arms pressed into it with 240 N on the chest and 110 N on each
    forearm, and every newton of that reacted into the robot and shoved it
    backwards. The pelvis retreated 0.44 m during the embrace and the
    policy leaned back to cope. Welded to the torso, the same squeeze is
    internal to the robot-plus-box system and the net external force is
    zero, which is also what holding a box against your chest actually is.
    """
    e = mujoco.mj_name2id(model, mujoco.mjtObj.mjOBJ_EQUALITY, "grab")
    if e < 0:
        return
    p1 = np.array(data.xpos[rig.torso_bid])
    q1 = np.array(data.xquat[rig.torso_bid])
    p2 = np.array(data.xpos[rig.box_bid])
    q2 = np.array(data.xquat[rig.box_bid])
    q1i = np.zeros(4); mujoco.mju_negQuat(q1i, q1)
    rel_pos = np.zeros(3); mujoco.mju_rotVecQuat(rel_pos, p2 - p1, q1i)
    rel_quat = np.zeros(4); mujoco.mju_mulQuat(rel_quat, q1i, q2)
    model.eq_data[e, 3:6] = rel_pos
    model.eq_data[e, 6:10] = rel_quat
    data.eq_active[e] = 1


def drop_to_ground(model, data, rig):
    """Put the base at the height the squat stance actually stands at.

    mj_resetData starts the robot at qpos0, which is the straight-leg
    height, but the policy immediately drives the legs to LEG_DEFAULT -- a
    slight squat. The pelvis then falls about 5 cm in the first second, and
    the box, which tracks the torso, falls with it. That is not the robot
    losing balance; it is the robot being born at the wrong height. Measure
    the difference by forward kinematics and start it where it belongs.
    """
    foot = mujoco.mj_name2id(model, mujoco.mjtObj.mjOBJ_BODY,
                             "left_ankle_roll_link")
    if foot < 0:
        return
    data.qpos[7:7 + rig.nj] = 0.
    mujoco.mj_forward(model, data)
    z_straight = float(data.xpos[foot][2])
    data.qpos[7:7 + rig.nj] = rig.full_q(np.zeros(rig.n_upper))
    mujoco.mj_forward(model, data)
    z_squat = float(data.xpos[foot][2])
    data.qpos[2] += z_straight - z_squat
    mujoco.mj_forward(model, data)


def stand_pose(model, rig):
    """A pinned-base standing configuration to run the search against."""
    data = mujoco.MjData(model)
    mujoco.mj_resetData(model, data)
    drop_to_ground(model, data, rig)
    return data


def search(model, rig, args, hx, hy, hz, front_t):
    """Two stages. Geometric first, because it costs half a millisecond and
    can therefore sweep the whole space; physical second, because a pose the
    controller cannot hold is not a pose."""
    data = stand_pose(model, rig)
    base = data.qpos[:7].copy()

    if args.quick:
        zs = [0.12]
        presses = [0.004]
        pitches = np.linspace(-1.25, -0.30, 5)
        rolls = np.linspace(-0.30, 0.35, 3)
        yaws = np.linspace(-1.50, 0.30, 4)
        elbows = np.linspace(-1.50, 0.30, 4)
    else:
        zs = [0.09, 0.13, 0.17]
        presses = [0.002, 0.006]
        # Capped short of a fully horizontal shoulder. At pitch -1.54
        # (88 degrees) the arms reach straight out, the centre of mass
        # moves far enough forward that the walking policy lost the robot
        # two steps in, and nothing about the hug needed that much flexion.
        pitches = np.linspace(-1.25, -0.25, 8)
        rolls = np.linspace(-0.35, 0.35, 5)
        yaws = np.linspace(-1.60, 0.40, 7)
        elbows = np.linspace(-1.60, 0.40, 7)

    total = (len(zs) * len(presses) * len(pitches) * len(rolls)
             * len(yaws) * len(elbows))
    print("=" * 74)
    print("STAGE 1  geometric sweep, in the torso's frame")
    print("=" * 74)
    print(f"  chest surface at torso-frame x {front_t:+.3f}")
    print(f"  {total} candidates: {len(zs)} box height x {len(presses)} press"
          f" x {len(pitches)} pitch x {len(rolls)} roll x {len(yaws)} yaw"
          f" x {len(elbows)} elbow")

    results, rejected, done = [], {}, 0
    t0 = time.time()
    for bz in zs:
        for press in presses:
            offset = np.array([front_t - press + hx, 0., bz])
            for p in pitches:
                for r in rolls:
                    for y in yaws:
                        for e in elbows:
                            done += 1
                            if rig.clipped(p, r, y, e):
                                continue
                            data.qpos[:7] = base
                            data.qvel[:] = 0.
                            data.qpos[7:7 + rig.nj] = rig.full_q(
                                rig.upper(p, r, y, e))
                            mujoco.mj_forward(model, data)
                            rig.put_box(data, offset)
                            mujoco.mj_forward(model, data)
                            hits, pen, faces = rig.zone_hits(data)
                            live = int((hits[rig.live_idx] > 0).sum())
                            if live < 3:
                                continue
                            ok, why = rig.face_check(faces)
                            if ok:
                                ok, why = rig.wrap_check(data, hx, hy, hz)
                            if not ok:
                                rejected[why] = rejected.get(why, 0) + 1
                                continue
                            q = rig.wrap_quality(data, hx, hy, hz)
                            fa = min(hits[PATCHES.index("left_lower_arm")],
                                     hits[PATCHES.index("right_lower_arm")])
                            ua = min(hits[PATCHES.index("left_upper_arm")],
                                     hits[PATCHES.index("right_upper_arm")])
                            score = (1000. * live + 300. * q
                                     + 25. * min(fa, 8)
                                     + 25. * min(ua, 8)
                                     - 150. * max(0., pen - 0.03))
                            results.append((score, live, pen, q, bz, press,
                                            p, r, y, e))
            print(f"  box z {bz:+.2f} press {press*1000:.0f}mm: "
                  f"{done}/{total}, {len(results)} viable, "
                  f"{time.time()-t0:.0f}s")

    if rejected:
        print("\n  lit three or more pads but were NOT a hug:")
        for why, k in sorted(rejected.items(), key=lambda kv: -kv[1])[:10]:
            print(f"    {k:6d}  {why}")
    if not results:
        print("\n  Nothing passed. The box may be too deep to reach around:")
        print("    the forearm is 0.10 m and the whole arm reaches 0.29 m,")
        print("    so a depth much over 0.17 m cannot be wrapped.")
        print("  Try:  python hug_walk.py --box 0.14 0.275 0.157")
        raise SystemExit(1)

    results.sort(key=lambda r: -r[0])
    print(f"\n  {'live':>5s} {'wrap':>6s} {'pen':>7s} {'boxz':>6s} "
          f"{'press':>6s} {'pitch':>7s} {'roll':>7s} {'yaw':>7s} "
          f"{'elbow':>7s}")
    for r in results[:args.finalists]:
        print(f"  {r[1]:4d}/5 {r[3]:6.3f} {r[2]:7.4f} {r[4]:+6.2f} "
              f"{r[5]:6.3f} {r[6]:+7.2f} {r[7]:+7.2f} {r[8]:+7.2f} "
              f"{r[9]:+7.2f}")

    # ---- stage 2 --------------------------------------------------------
    print()
    print("=" * 74)
    print("STAGE 2  real controller, real sensors, base pinned")
    print("=" * 74)
    print(f"  {'#':>3s} {'boxz':>6s} {'pose':>28s} {'live':>5s} "
          f"{'steady':>7s} {'held':>6s} {'weakest':>8s} {'err':>7s}")
    print(f"       held: C=chest U/L=left upper/lower u/l=right upper/lower")
    tried, measured = [], []
    for rank, r in enumerate(results[:args.finalists], 1):
        _, live, pen, qq, bz, press, p, rl, y, e = r
        offset = np.array([front_t - press + hx, 0., bz])
        mean, mins, err = physics_trial(model, rig, p, rl, y, e, offset,
                                        arm_kp=args.arm_kp,
                                        arm_kd=args.arm_kd)
        nlive = int((mean[rig.live_idx] > TOUCH_ON).sum())
        held = int((mins[rig.live_idx] > TOUCH_ON).sum())
        weakest = float(np.min(mins[rig.live_idx]))
        ok = held == len(LIVE) and err < args.max_err
        # Which pads held, not just how many. The count hid the real
        # behaviour: the upper arms and the forearms were taking turns,
        # because the forearm pressing on the front face levers the upper
        # arm off the side face.
        tag = "".join(
            (lbl if mins[PATCHES.index(pad)] > TOUCH_ON else ".")
            for pad, lbl in (("chest", "C"), ("left_upper_arm", "U"),
                             ("left_lower_arm", "L"),
                             ("right_upper_arm", "u"),
                             ("right_lower_arm", "l")))
        print(f"  {rank:3d} {bz:+6.2f} ({p:+.2f},{rl:+.2f},{y:+.2f},"
              f"{e:+.2f}) {nlive:4d}/5 {held:6d}/5 {tag:>6s} "
              f"{weakest:8.2f} {err:+7.3f}"
              + ("" if ok else "   rejected"))
        measured.append((weakest, held, bz, press, p, rl, y, e))
        if ok:
            tried.append((weakest, mean, mins, bz, press, p, rl, y, e))
    if tried:
        tried.sort(key=lambda t: -t[0])
        weakest, mean, mins, bz, press, p, rl, y, e = tried[0]
        print(f"\n  CHOSEN  box z {bz:+.2f}, press {press*1000:.0f} mm, "
              f"pose ({p:+.2f},{rl:+.2f},{y:+.2f},{e:+.2f})")
        print(f"  weakest live pad holds {weakest:.2f} N")
        for k, pad in enumerate(PATCHES):
            flag = "   (back: expected silent)" if pad not in LIVE else ""
            print(f"    {pad:17s} {mean[k]:8.2f} N  min {mins[k]:8.2f} N"
                  f"{flag}")
    elif measured:
        # Falling back to the best GEOMETRIC result was wrong: geometry
        # said five pads touch, the controller delivered three, and the run
        # then walked with a pose already known to be loose. Fall back to
        # the best thing actually measured instead.
        measured.sort(key=lambda t: (-t[0], -t[1]))
        weakest, nheld, bz, press, p, rl, y, e = measured[0]
        print(f"\n  No candidate held all five under the controller.")
        print(f"  Best MEASURED result: {nheld}/5 pads steady, weakest "
              f"{weakest:.2f} N, pose ({p:+.2f},{rl:+.2f},{y:+.2f},{e:+.2f})")
        print("  Raising --arm-kp is usually what fixes this: a tracking")
        print("  error of a few tenths of a radian means the arm stopped")
        print("  short of the box instead of pressing into it.")
    else:
        _, live, pen, qq, bz, press, p, rl, y, e = results[0]
        print("\n  Nothing measurable. Falling back to the geometric best.")
    return bz, press, p, rl, y, e


def physics_trial(model, rig, p, rl, y, e, offset, seconds=3.5,
                  arm_kp=ARM_KP, arm_kd=ARM_KD):
    """Close the arms the way the run closes them, then read the sensors.

    The first version stepped the target straight to the wrapped pose. The
    arms then slammed into the box and rebounded, and the upper-arm pads
    happened to be off the box during the measuring window -- so stage 2
    reported C.L.l for every candidate and rejected the lot, while the
    actual run, which ramps the same pose in over 2.5 s, held 5/5 with
    160-250 N on those very pads. The test was wrong, not the poses. It
    now ramps over the first 60% and measures only after it has settled.
    """
    data = mujoco.MjData(model)
    mujoco.mj_resetData(model, data)
    drop_to_ground(model, data, rig)
    base = data.qpos[:7].copy()
    legs0 = data.qpos[7:19].copy()
    rig.put_box(data, offset)
    mujoco.mj_forward(model, data)
    weld_box_to_torso(model, data, rig)
    target = rig.upper(p, rl, y, e)
    start = np.zeros(rig.n_upper)
    n = int(seconds / model.opt.timestep)
    ramp = int(0.6 * n)
    tail = max(1, n // 6)
    acc = np.zeros(len(PATCHES))
    mins = np.full(len(PATCHES), np.inf)
    for i in range(n):
        k = ease(i / max(ramp, 1)) if i < ramp else 1.0
        now = start + (target - start) * k
        data.ctrl[:12] = (legs0 - data.qpos[7:19]) * LEG_KP \
            - data.qvel[6:18] * LEG_KD
        data.ctrl[12:] = (now - data.qpos[19:7 + rig.nj]) * arm_kp \
            - data.qvel[18:6 + rig.nj] * arm_kd
        mujoco.mj_step(model, data)
        data.qpos[:7] = base
        data.qvel[:6] = 0.
        if i >= n - tail:
            v = data.sensordata[rig.touch_adr]
            acc += v
            mins = np.minimum(mins, v)
    got = data.qpos[19:7 + rig.nj]
    err = float(np.max(np.abs(target - got)))
    return acc / tail, mins, err


